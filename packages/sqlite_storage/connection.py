"""SQLCipher connections used by the desktop backend."""

from __future__ import annotations

from contextlib import contextmanager
from pathlib import Path
from typing import Iterator

from packages.sqlite_storage.credentials import (
    CredentialManagerKeyStore,
    database_path_from_environment,
)


def _driver():
    try:
        from sqlcipher3 import dbapi2 as sqlite
    except ImportError as exc:
        raise RuntimeError(
            "SQLCipher is not installed. Install sqlcipher3-wheels for the "
            "desktop backend; standard sqlite3 is intentionally not allowed."
        ) from exc
    return sqlite


def database_path() -> Path:
    return database_path_from_environment()


@contextmanager
def connect() -> Iterator[object]:
    sqlite = _driver()
    path = database_path()
    key = CredentialManagerKeyStore(path).get_or_create()
    connection = sqlite.connect(str(path), timeout=30)
    try:
        # PRAGMA does not accept DB-API placeholders. The key is generated by
        # this application as hex, so quoting it here is safe.
        escaped_key = key.replace("'", "''")
        connection.execute(f"PRAGMA key = '{escaped_key}'")
        connection.execute("PRAGMA cipher_compatibility = 4")
        connection.execute("PRAGMA foreign_keys = ON")
        connection.execute("PRAGMA busy_timeout = 5000")
        connection.execute("PRAGMA journal_mode = WAL")
        connection.execute("PRAGMA synchronous = NORMAL")
        # Force key validation immediately. A wrong/corrupt key must not look
        # like an empty database to the application.
        connection.execute("SELECT count(*) FROM sqlite_master").fetchone()
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def check_connection() -> bool:
    with connect() as connection:
        return connection.execute("SELECT 1").fetchone()[0] == 1
